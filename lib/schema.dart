import 'package:powersync/powersync.dart';

// Columnas numéricas como Column.text a propósito (recomendación oficial de
// PowerSync para no perder precisión con el tipo `numeric` de Postgres).
const schema = Schema([
  Table('depositos', [Column.text('nombre'), Column.text('creado_en')]),
  Table('productos', [
    Column.text('nombre'),
    Column.text('sku'),
    Column.text('precio'),
    Column.text('costo'),
    Column.text('categoria'),
    Column.text('stock_minimo'),
    Column.text('activo'),
    Column.text('creado_en'),
  ]),
  Table('movimientos_stock', [
    Column.text('producto_id'),
    Column.text('deposito_id'),
    Column.text('cantidad'),
    Column.text('motivo'),
    Column.text('venta_id'),
    Column.text('orden_id'),
    Column.text('creado_en'),
  ]),
  Table('ventas', [
    Column.text('deposito_id'),
    Column.text('total'),
    Column.text('estado'),
    Column.text('cliente_id'),
    Column.text('creado_en'),
  ]),
  Table('pagos_venta', [
    Column.text('venta_id'),
    Column.text('metodo'),
    Column.text('monto'),
    Column.text('efectivo_recibido'),
    Column.text('vuelto'),
    Column.text('creado_en'),
  ]),
  Table('perfiles', [
    Column.text('email'),
    Column.text('nombre'),
    Column.text('creado_en'),
  ]),
  Table('configuracion_tienda', [
    Column.text('nombre'),
    Column.text('direccion'),
    Column.text('horario_apertura'),
    Column.text('horario_cierre'),
    Column.text('moneda'),
    Column.text('notif_banner_revision'),
    Column.text('notif_stock_minimo_default'),
    Column.text('creado_en'),
  ]),
  Table('clientes', [
    Column.text('nombre'),
    Column.text('telefono'),
    Column.text('email'),
    Column.text('notas'),
    Column.text('creado_en'),
  ]),
  Table('cajas', [
    Column.text('deposito_id'),
    Column.text('monto_apertura'),
    Column.text('abierta_por'),
    Column.text('cerrada_en'),
    Column.text('monto_cierre_esperado'),
    Column.text('monto_cierre_real'),
    Column.text('diferencia'),
    Column.text('cerrada_por'),
    Column.text('estado'),
    Column.text('notas'),
    Column.text('creado_en'),
  ]),
  Table('movimientos_caja', [
    Column.text('caja_id'),
    Column.text('tipo'),
    Column.text('monto'),
    Column.text('motivo'),
    Column.text('creado_por'),
    Column.text('creado_en'),
  ]),
  Table('ordenes_compra', [
    Column.text('proveedor'),
    Column.text('estado'),
    Column.text('notas'),
    Column.text('creado_por'),
    Column.text('recibida_en'),
    Column.text('recibida_por'),
    Column.text('creado_en'),
  ]),
  Table('orden_compra_items', [
    Column.text('orden_id'),
    Column.text('producto_id'),
    Column.text('cantidad'),
    Column.text('costo_unitario'),
    Column.text('creado_en'),
  ]),
]);
